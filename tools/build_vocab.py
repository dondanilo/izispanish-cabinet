def parse(src):
    """Вернуть (before, cats, after). cats — список dict{id,emoji,title,words[]}."""
    m = re.search(r"(const VOCAB_CATEGORIES\s*=\s*\[\n)(.*?)(\n\];)", src, re.S)
    if not m:
        sys.exit("не найден блок VOCAB_CATEGORIES")
    before = src[:m.start(2)]
    after = src[m.end(2):]
    blk = m.group(2)
    cats = []
    # категории разделены строкой, начинающейся с "  {"
    chunks = re.split(r"\n(?=  \{\n)", blk)
    for ch in chunks:
        cid = re.search(r"id:\s*'([^']+)'", ch)
        if not cid:
            continue
        emoji = re.search(r"emoji:\s*'([^']*)'", ch)
        title = re.search(r"title:\s*'([^']+)'", ch)
        words = []
        for wm in re.finditer(
            r"\{\s*greek:\s*'((?:[^'\\]|\\.)*)',\s*transcription:\s*'((?:[^'\\]|\\.)*)',"
            r"\s*translation:\s*'((?:[^'\\]|\\.)*)',\s*emoji:\s*'((?:[^'\\]|\\.)*)'\s*\}",
            ch):
            words.append(dict(greek=wm.group(1), transcription=wm.group(2),
                              translation=wm.group(3), emoji=wm.group(4)))
        cats.append(dict(id=cid.group(1),
                         emoji=emoji.group(1) if emoji else '',
                         title=title.group(1) if title else '',
                         words=words))
    return before, cats, after


def esc(s):
    return s.replace("\\", "\\\\").replace("'", "\\'")


def render(cats):
    blocks = []
    for c in cats:
        wlines = [
            (f"      {{ greek: '{esc(w['greek'])}', transcription: '{esc(w['transcription'])}', "
             f"translation: '{esc(w['translation'])}', emoji: '{esc(w['emoji'])}' }}")
            for w in c['words']
        ]
        block = (
            "  {\n"
            f"    id: '{esc(c['id'])}', emoji: '{esc(c['emoji'])}', title: '{esc(c['title'])}',\n"
            "    words: [\n"
            + ",\n".join(wlines) + "\n"
            "    ]\n"
            "  }"
        )
        blocks.append(block)
    return ",\n".join(blocks) + ","   # висячая запятая — как в оригинале


def main():
    src = DATA.read_text(encoding="utf-8")
    before, cats, after = parse(src)

    if "--check" in sys.argv:
        rebuilt = before + render(cats) + after
        ok = rebuilt == src
        print("ROUNDTRIP:", "ИДЕНТИЧНО" if ok else "ОТЛИЧАЕТСЯ")
        if not ok:
            # показать первую точку расхождения
            for i, (a, b) in enumerate(zip(src, rebuilt)):
                if a != b:
                    print("разошлось на позиции", i)
                    print("было :", repr(src[i:i+80]))
                    print("стало:", repr(rebuilt[i:i+80]))
                    break
        for c in cats:
            print(f"  {c['id']:16} {len(c['words'])}")
        return

    added_total = 0
    for c in cats:
        extra = EXTRA.get(c['id'])
        if not extra:
            continue
        seen = {w['greek'].lower() for w in c['words']}
        for esp, tr, ru, em in extra:
            if esp.lower() in seen:
                continue
            seen.add(esp.lower())
            c['words'].append(dict(greek=esp, transcription=tr, translation=ru, emoji=em))
            added_total += 1

    rebuilt = before + render(cats) + after
    DATA.write_text(rebuilt, encoding="utf-8")
    print(f"добавлено записей: {added_total}")
    for c in cats:
        if c['id'] in EXTRA:
            print(f"  {c['id']:16} → {len(c['words'])}")


if __name__ == "__main__":
    main()
